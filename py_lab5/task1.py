# 14.В массиве найти элементы, которые в нем встречаются только один раз, и вывести их на экран. 
# То есть найти и вывести уникальные элементы массива.


input_str = input("Введите элементы массива через пробел (целые числа): ")
arr = [int(x) for x in input_str.split()]
unique_elements = [x for x in arr if arr.count(x) == 1]
print("Исходный массив:", arr) 
print("Элементы, которые встречаются только один раз:", unique_elements)
